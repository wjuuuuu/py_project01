# 案例 1：键盘输入一个整数，判断这个数字是否在 10～20之间 --->在：True，不在：False
n = int(input("请输入一个整数:"))

print(f"{n} 在10～20之间:",n >= 10 and n <= 20)

# 案例 2：键盘输入一个整数，判断这个数字是否不在 10～20之间
n = int(input("请输入一个整数:"))

print(f"{n} 不在10～20之间:",n < 10 or n > 20)
